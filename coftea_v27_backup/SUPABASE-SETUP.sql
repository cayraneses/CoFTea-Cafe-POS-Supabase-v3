create or replace function public.save_sale(p_sale_id bigint, p_items jsonb, p_payment text, p_cash numeric, p_user_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_sale_id bigint; v_tx text; v_total numeric(12,2); v_cash numeric(12,2); v_change numeric(12,2); v_date date:=current_date; v_time time:=localtime; r record; cup_qty numeric; inv record;
begin
 if jsonb_array_length(coalesce(p_items,'[]'::jsonb))=0 then raise exception 'Order is empty.'; end if;
 select coalesce(sum((x->>'lineTotal')::numeric*greatest(1,coalesce((x->>'qty')::numeric,1))),0) into v_total from jsonb_array_elements(p_items)x;
 v_cash:=case when p_payment='Cash' then greatest(0,coalesce(p_cash,0)) else 0 end;
 if p_payment='Cash' and v_cash<v_total then raise exception 'Cash received is less than total.'; end if;
 v_change:=case when p_payment='Cash' then v_cash-v_total else 0 end;
 if p_sale_id is not null then
   select * into r from public.sales where id=p_sale_id and status='completed' for update; if not found then raise exception 'Sale not found.'; end if;
   for r in select case when size='12oz' then '12 oz' when size='16oz' then '16 oz' when size='22oz' then '22 oz' else 'Hot Cups' end cname,sum(quantity) qty from public.sale_items where sale_id=p_sale_id group by 1 loop update public.inventory set outside=outside+r.qty,updated_at=now() where name=r.cname; end loop;
   delete from public.sale_items where sale_id=p_sale_id;
   update public.sales set sale_date=v_date,sale_time=v_time,subtotal=v_total,total=v_total,payment_method=p_payment,cash_received=v_cash,change_amount=v_change,user_id=coalesce(p_user_id,user_id),updated_at=now() where id=p_sale_id;
   v_sale_id:=p_sale_id; select transaction_id into v_tx from public.sales where id=v_sale_id;
 else
   v_tx:='TRX-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
   insert into public.sales(transaction_id,sale_date,sale_time,subtotal,total,payment_method,cash_received,change_amount,user_id,status) values(v_tx,v_date,v_time,v_total,v_total,p_payment,v_cash,v_change,p_user_id,'completed') returning id into v_sale_id;
 end if;
 for r in select case when x->>'size'='12oz' then '12 oz' when x->>'size'='16oz' then '16 oz' when x->>'size'='22oz' then '22 oz' else 'Hot Cups' end cname,sum(greatest(1,coalesce((x->>'qty')::numeric,1))) qty from jsonb_array_elements(p_items)x group by 1 loop
   select * into inv from public.inventory where name=r.cname for update;
   if found and coalesce(inv.inside,0)+coalesce(inv.outside,0)+coalesce(inv.stock_in,0)+coalesce(inv.adjustments,0)<r.qty then raise exception 'Not enough % cups. Remaining: %',r.cname,(coalesce(inv.inside,0)+coalesce(inv.outside,0)+coalesce(inv.stock_in,0)+coalesce(inv.adjustments,0)); end if;
   if found then cup_qty:=least(coalesce(inv.outside,0),r.qty); update public.inventory set outside=outside-cup_qty,inside=greatest(0,inside-(r.qty-cup_qty)),updated_at=now() where id=inv.id; end if;
 end loop;
 insert into public.sale_items(sale_id,product_name,category,size,temperature,quantity,unit_price,addon,addon_price,tutti_frutti,free_upsize,original_size,free_drink,customized,line_total)
 select v_sale_id,x->>'product',coalesce(x->>'category',''),coalesce(x->>'size',''),coalesce(x->>'temperature','Cold'),greatest(1,coalesce((x->>'qty')::numeric,1)),coalesce((x->>'unit')::numeric,0),coalesce(x->>'addon','No Add-on'),coalesce((x->>'addonPrice')::numeric,0),coalesce((x->>'tutti')::boolean,false),coalesce((x->>'freeUpsize')::boolean,false),nullif(x->>'originalSize',''),coalesce((x->>'freeDrink')::boolean,false),coalesce((x->>'customized')::boolean,false),coalesce((x->>'lineTotal')::numeric,0) from jsonb_array_elements(p_items)x;
 return jsonb_build_object('ok',true,'transactionId',v_tx);
end; $$;
create or replace function public.delete_sale(p_sale_id bigint) returns jsonb language plpgsql security definer set search_path=public as $$ declare r record; begin select * into r from public.sales where id=p_sale_id and status='completed' for update; if not found then raise exception 'Sale not found.'; end if; for r in select case when size='12oz' then '12 oz' when size='16oz' then '16 oz' when size='22oz' then '22 oz' else 'Hot Cups' end cname,sum(quantity) qty from public.sale_items where sale_id=p_sale_id group by 1 loop update public.inventory set outside=outside+r.qty,updated_at=now() where name=r.cname; end loop; update public.sales set status='deleted',updated_at=now() where id=p_sale_id; return jsonb_build_object('ok',true); end; $$;
