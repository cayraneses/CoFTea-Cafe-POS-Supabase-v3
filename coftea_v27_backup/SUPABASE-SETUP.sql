create table if not exists public.app_users (id bigint generated by default as identity primary key, auth_user_id uuid unique references auth.users(id) on delete cascade, email text unique not null, username text unique not null, name text not null default '', role text not null default 'staff' check (role in ('owner','staff')), active boolean not null default true, created_at timestamptz not null default now());
create table if not exists public.products (id bigint generated by default as identity primary key, product_id text unique not null, category text not null, name text not null, p12 numeric(10,2) not null default 0, p16 numeric(10,2) not null default 0, p22 numeric(10,2) not null default 0, active boolean not null default true, unique(category,name));
create table if not exists public.inventory (id bigint generated by default as identity primary key, sku text unique not null, name text not null, category text not null, unit text not null default 'pcs', inside numeric(12,2) not null default 0, outside numeric(12,2) not null default 0, stock_in numeric(12,2) not null default 0, adjustments numeric(12,2) not null default 0, reorder numeric(12,2) not null default 0, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.sales (id bigint generated by default as identity primary key, transaction_id text unique not null, sale_date date not null, sale_time time not null, subtotal numeric(12,2) not null default 0, total numeric(12,2) not null default 0, payment_method text not null, cash_received numeric(12,2) not null default 0, change_amount numeric(12,2) not null default 0, user_id bigint references public.app_users(id), status text not null default 'completed', created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.sale_items (id bigint generated by default as identity primary key, sale_id bigint not null references public.sales(id) on delete cascade, product_name text not null, category text not null default '', size text not null default '', temperature text not null default 'Cold', quantity numeric(12,2) not null default 1, unit_price numeric(12,2) not null default 0, addon text not null default 'No Add-on', addon_price numeric(12,2) not null default 0, tutti_frutti boolean not null default false, free_upsize boolean not null default false, original_size text, free_drink boolean not null default false, customized boolean not null default false, line_total numeric(12,2) not null default 0);
create table if not exists public.expenses (id bigint generated by default as identity primary key, expense_date date not null, category text not null, description text not null, amount numeric(12,2) not null, payment_method text not null default 'Cash', notes text not null default '', created_at timestamptz not null default now());
create table if not exists public.historical (id bigint generated by default as identity primary key, record_date date not null, sales numeric(12,2) not null default 0, expenses numeric(12,2) not null default 0, cash_sales numeric(12,2) not null default 0, gcash_sales numeric(12,2) not null default 0, cash_expenses numeric(12,2) not null default 0, gcash_expenses numeric(12,2) not null default 0, cups numeric(12,2) not null default 0, notes text not null default '', created_at timestamptz not null default now());
create table if not exists public.report_adjustments (id bigint generated by default as identity primary key, type text not null check(type in ('daily','monthly','yearly')), key text not null, sales_delta numeric(12,2) not null default 0, cash_delta numeric(12,2) not null default 0, gcash_delta numeric(12,2) not null default 0, expenses_delta numeric(12,2) not null default 0, cups_delta numeric(12,2) not null default 0, updated_at timestamptz not null default now(), unique(type,key));

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$ begin insert into public.app_users(auth_user_id,email,username,name,role,active) values(new.id,new.email,coalesce(nullif(new.raw_user_meta_data->>'username',''),split_part(new.email,'@',1)),coalesce(nullif(new.raw_user_meta_data->>'name',''),split_part(new.email,'@',1)),case when lower(coalesce(new.raw_user_meta_data->>'role','staff'))='owner' then 'owner' else 'staff' end,true) on conflict (auth_user_id) do update set email=excluded.email; return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
create or replace function public.lookup_login_email(p_username text) returns table(email text, active boolean) language sql security definer set search_path=public as $$ select u.email,u.active from public.app_users u where lower(u.username)=lower(trim(p_username)) limit 1; $$;
grant execute on function public.lookup_login_email(text) to anon,authenticated;

create or replace function public.current_app_role() returns text language sql stable security definer set search_path=public as $$ select role from public.app_users where auth_user_id=auth.uid() and active=true limit 1; $$;

