const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("api", {
  login:(u,p)=>ipcRenderer.invoke("auth:login",u,p),
  account:get=>ipcRenderer.invoke("account:get",get),
  updateAccount:d=>ipcRenderer.invoke("account:update",d),
  changePassword:d=>ipcRenderer.invoke("auth:change",d),
  products:()=>ipcRenderer.invoke("products:list"),
  inventory:()=>ipcRenderer.invoke("inventory:list"),
  saveInventory:d=>ipcRenderer.invoke("inventory:save",d),
  deleteInventory:id=>ipcRenderer.invoke("inventory:delete",id),
  addInventory:d=>ipcRenderer.invoke("inventory:add",d),
  setInventory:d=>ipcRenderer.invoke("inventory:set",d),
  saveSale:d=>ipcRenderer.invoke("pos:save",d),
  updateSale:d=>ipcRenderer.invoke("pos:update",d),
  sales:d=>ipcRenderer.invoke("sales:list",d),
  deleteSale:id=>ipcRenderer.invoke("sales:delete",id),
  expenses:d=>ipcRenderer.invoke("expenses:list",d),
  addExpense:d=>ipcRenderer.invoke("expenses:add",d),
  deleteExpense:id=>ipcRenderer.invoke("expenses:delete",id),
  dashboard:()=>ipcRenderer.invoke("reports:dashboard"),
  monthly:()=>ipcRenderer.invoke("reports:monthly"),
  yearly:()=>ipcRenderer.invoke("reports:yearly"),
  dailyTracker:()=>ipcRenderer.invoke("reports:daily"),
  reportAdjustmentGet:(type,key)=>ipcRenderer.invoke("reports:adjustment:get",type,key),
  reportAdjustmentSave:d=>ipcRenderer.invoke("reports:adjustment:save",d),
  reportAdjustmentDelete:(type,key)=>ipcRenderer.invoke("reports:adjustment:delete",type,key),
  cupSummary:d=>ipcRenderer.invoke("cups:summary",d),
  historical:d=>ipcRenderer.invoke("history:list",d),
  addHistorical:d=>ipcRenderer.invoke("history:add",d),
  backup:()=>ipcRenderer.invoke("settings:backup"),
  restore:()=>ipcRenderer.invoke("settings:restore"),
});
